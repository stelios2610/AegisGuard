#!/bin/bash
# AegisGuard First Boot Setup
# Runs once after installation to configure the network and start services.

set -e

LOGFILE="/var/log/aegisguard-firstboot.log"
DONE_FLAG="/etc/aegisguard/.firstboot_done"

exec > >(tee -a "$LOGFILE") 2>&1

log() { echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*"; }

# Run only once
if [ -f "$DONE_FLAG" ]; then
    log "First-boot already completed. Skipping."
    exit 0
fi

log "=== AegisGuard First Boot Setup ==="
mkdir -p /etc/aegisguard

# ── 1. Detect actual interface names ─────────────────────────────────────────
# On some systems (Hyper-V, VMs) interfaces may be named eth0/eth1 or
# enp2s0/enp3s0 etc. We map the first two to WAN and LAN.

IFACES=($(ls /sys/class/net | grep -v lo | sort))
WAN_IF="${IFACES[0]:-eth0}"
LAN_IF="${IFACES[1]:-eth1}"

log "Detected interfaces: WAN=$WAN_IF  LAN=$LAN_IF"

# ── 2. Write /etc/network/interfaces ─────────────────────────────────────────
cat > /etc/network/interfaces << EOF
# AegisGuard network configuration
# Generated by first-boot setup

source /etc/network/interfaces.d/*

auto lo
iface lo inet loopback

# WAN — DHCP from ISP
auto ${WAN_IF}
iface ${WAN_IF} inet dhcp

# LAN — Static 10.0.0.1/24
auto ${LAN_IF}
iface ${LAN_IF} inet static
    address 10.0.0.1
    netmask 255.255.255.0
    # No gateway on LAN interface
EOF

log "Written /etc/network/interfaces"

# ── 3. Bring up interfaces ────────────────────────────────────────────────────
ifdown --all --ignore-errors 2>/dev/null || true
sleep 1

# Bring up LAN first (so web UI is reachable immediately)
ip link set "${LAN_IF}" up
ip addr flush dev "${LAN_IF}" 2>/dev/null || true
ip addr add 10.0.0.1/24 dev "${LAN_IF}"
log "LAN interface ${LAN_IF} up: 10.0.0.1/24"

# Bring up WAN via DHCP
ip link set "${WAN_IF}" up
dhclient -v "${WAN_IF}" 2>/dev/null || true
log "WAN interface ${WAN_IF} configured via DHCP"

# ── 4. Enable IP forwarding (router mode) ─────────────────────────────────────
echo 1 > /proc/sys/net/ipv4/ip_forward
sed -i 's/#net.ipv4.ip_forward=1/net.ipv4.ip_forward=1/' /etc/sysctl.conf
sysctl -w net.ipv4.ip_forward=1
log "IP forwarding enabled"

# ── 5. NAT masquerade on WAN (so LAN clients get internet) ───────────────────
iptables -t nat -A POSTROUTING -o "${WAN_IF}" -j MASQUERADE
iptables -A FORWARD -i "${LAN_IF}" -o "${WAN_IF}" -j ACCEPT
iptables -A FORWARD -m state --state ESTABLISHED,RELATED -j ACCEPT
log "NAT/masquerade set on ${WAN_IF}"

# Save iptables rules
iptables-save > /etc/iptables/rules.v4 2>/dev/null || true

# ── 6. Update AegisGuard DB with detected interface names ─────────────────────
python3 - << PYEOF
import sys
sys.path.insert(0, '/opt/aegisguard')
from db import database

database.initialize()

# Update interface names if they differ from defaults
conn = database.get_connection()
conn.execute("UPDATE interfaces SET name=? WHERE role='WAN'", ('${WAN_IF}',))
conn.execute("UPDATE interfaces SET name=? WHERE role='LAN'", ('${LAN_IF}',))
conn.execute("UPDATE dhcp_config SET interface=? WHERE interface='eth1'", ('${LAN_IF}',))
conn.execute("INSERT OR REPLACE INTO settings (key,value) VALUES ('wan_interface','${WAN_IF}')")
conn.execute("INSERT OR REPLACE INTO settings (key,value) VALUES ('lan_interface','${LAN_IF}')")
conn.commit()
conn.close()
print("Database updated with interface names")
PYEOF

# ── 7. Write dnsmasq DHCP config ──────────────────────────────────────────────
mkdir -p /etc/dnsmasq.d
cat > /etc/dnsmasq.d/aegisguard.conf << EOF
# AegisGuard DHCP server on LAN
interface=${LAN_IF}
bind-interfaces
dhcp-range=${LAN_IF},10.0.0.100,10.0.0.200,255.255.255.0,24h
dhcp-option=${LAN_IF},3,10.0.0.1
dhcp-option=${LAN_IF},6,1.1.1.1,8.8.8.8
domain=aegis.local
local=/aegis.local/
bogus-priv
domain-needed
no-resolv
server=1.1.1.1
server=8.8.8.8
EOF

systemctl enable dnsmasq
systemctl restart dnsmasq
log "dnsmasq DHCP server started on ${LAN_IF} (10.0.0.100-200)"

# ── 8. Firewall: EVERYTHING only from LAN — WAN fully locked ─────────────────
# Flush existing INPUT rules
iptables -F INPUT

# Allow loopback
iptables -A INPUT -i lo -j ACCEPT

# Allow established/related (return traffic from internet)
iptables -A INPUT -m state --state ESTABLISHED,RELATED -j ACCEPT

# Allow EVERYTHING from LAN interface (web UI, SSH, DHCP, etc.)
iptables -A INPUT -i "${LAN_IF}" -j ACCEPT

# Block ALL inbound from WAN — no exceptions
iptables -A INPUT -i "${WAN_IF}" -j DROP

# Default policy: drop anything else
iptables -P INPUT DROP

iptables-save > /etc/iptables/rules.v4
log "Firewall: WAN fully locked. ALL access via LAN (${LAN_IF}) only."

# ── 9. Start AegisGuard ───────────────────────────────────────────────────────
systemctl enable aegisguard
systemctl start aegisguard
log "AegisGuard started"

# ── 10. Mark first boot as done ───────────────────────────────────────────────
touch "$DONE_FLAG"

log "=== First boot complete ==="
log "Web UI: http://10.0.0.1:8080"
log "Connect a PC to ${LAN_IF}, get IP from DHCP (10.0.0.x), open browser."
